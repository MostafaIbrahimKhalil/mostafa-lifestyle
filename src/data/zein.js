// فكرة النهارده: بتتغير كل يوم، ولو دوست "فكرة تانية" بتتنقل للي بعدها
export function zeinIdea(dateKeyStr, shift = 0) {
  const [y, m, d] = dateKeyStr.split('-').map(Number)
  const dayNo = Math.floor(Date.UTC(y, m - 1, d) / 86400000)
  return ZEIN_IDEAS[(((dayNo + shift) % ZEIN_IDEAS.length) + ZEIN_IDEAS.length) % ZEIN_IDEAS.length]
}
